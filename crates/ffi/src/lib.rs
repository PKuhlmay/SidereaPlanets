//! UniFFI interface of the session for the native Mac app (`mac/`, SwiftUI).
//!
//! [`CoreSession`] wraps one [`planets_session::Session`] and exposes every step of the workflow
//! (Open, Alignpoints, Align, Limit, Stack, Wavelets, colour panels, Save, project file, schemes,
//! Cancel and Pause, CPUs). Requests and results are UniFFI records and enums that mirror the types
//! of the session ([`types`]); the conversion is the only code in here, there is no logic of its own.
//!
//! - Images cross as [`RgbaImage`]: width, height and RGBA8 bytes.
//! - Errors are [`PlanetsError`]; every variant carries the text of the session error.
//! - Progress goes to a [`ProgressListener`] that Swift implements.
//! - Align, Stack, Wavelet Do All and Save Aligned/Integrated **block** the calling thread until they
//!   are done; the Swift layer (`mac/Packages/SidereaPlanetsKit`) runs them off the main thread. `cancel`
//!   and `pause` can be called from another thread meanwhile.
//!
//! # `unsafe`
//!
//! The workspace forbids `unsafe_code`, and this crate does not inherit that lint (see `Cargo.toml`):
//! the scaffolding generated by `uniffi::setup_scaffolding!` and the derive macros is `extern "C"`
//! code that cannot be written without `unsafe`. Nothing hand-written here uses it; all other crates
//! keep `forbid`.

mod error;
mod types;

pub use error::PlanetsError;
pub use types::*;

use planets_session as session;
use std::{path::Path, sync::Arc};

uniffi::setup_scaffolding!();

/// Hands the progress of the session to a foreign [`ProgressListener`].
struct ListenerSink(Arc<dyn ProgressListener>);

impl session::ProgressSink for ListenerSink {
    fn progress(&self, operation: session::Operation, done: u32, total: u32, elapsed_ms: u64) {
        self.0.progress(operation.into(), done, total, elapsed_ms);
    }
}

type Result<T> = std::result::Result<T, PlanetsError>;

/// One open recording and the work built on it: the state behind the workflow steps. All methods can
/// be called from any thread; `cancel` and `pause` also while another thread runs an operation.
#[derive(uniffi::Object)]
pub struct CoreSession {
    inner: Arc<session::Session>,
}

#[uniffi::export]
impl CoreSession {
    /// A session without a recording that calculates on all logical cores.
    #[uniffi::constructor]
    pub fn new() -> Result<Arc<Self>> {
        Ok(Arc::new(Self {
            inner: Arc::new(session::Session::new()?),
        }))
    }

    // --- Open ----------------------------------------------------------------------------------

    /// Opens one video, or one or more still frames as a sequence.
    pub fn open_recording(&self, paths: Vec<String>) -> Result<RecordingInfo> {
        let paths: Vec<_> = paths.into_iter().map(Into::into).collect();
        Ok(self.inner.open_recording(&paths)?.into())
    }

    /// One frame of the open recording (0-based).
    pub fn read_frame(&self, index: u32) -> Result<RgbaImage> {
        Ok(self.inner.read_frame(index)?.into())
    }

    // --- Align ---------------------------------------------------------------------------------

    /// Sets alignpoints on one frame, with the default threshold. Starts a new alignment: the old
    /// results and everything built on them are gone.
    pub fn set_alignpoints(&self, frame: u32, settings: PointSettings) -> Result<Alignpoints> {
        Ok(self.inner.set_alignpoints(frame, &settings.into())?.into())
    }

    /// Moves the *Threshold* slider.
    pub fn set_alignpoint_threshold(&self, threshold: u64) -> Result<Alignpoints> {
        Ok(self
            .inner
            .set_alignpoint_threshold(threshold as usize)?
            .into())
    }

    /// Aligns all frames to the reference frame and rates them. Blocks until done; stops on
    /// `cancel(SessionOperation::Align)` with `PlanetsError::Cancelled`.
    pub fn align(
        &self,
        settings: AlignSettings,
        progress: Arc<dyn ProgressListener>,
    ) -> Result<Aligned> {
        Ok(self
            .inner
            .align(&settings.into(), &ListenerSink(progress))?
            .into())
    }

    /// *Limit*: the frames that stay and the mean shift of every point over them.
    pub fn limit(&self, settings: LimitSettings) -> Result<Limited> {
        Ok(self.inner.limit(&settings.into())?.into())
    }

    // --- Stack ---------------------------------------------------------------------------------

    /// Registers the selected frames against the reference frame and stacks them. Blocks until done;
    /// stops on `cancel(SessionOperation::Stack)`.
    pub fn stack(
        &self,
        settings: StackSettings,
        progress: Arc<dyn ProgressListener>,
    ) -> Result<Stacked> {
        Ok(self
            .inner
            .stack(&settings.into(), &ListenerSink(progress))?
            .into())
    }

    /// The stacked image.
    pub fn stacked_image(&self) -> Result<RgbaImage> {
        Ok(self.inner.stacked_image()?.into())
    }

    // --- Wavelets ------------------------------------------------------------------------------

    /// Uses a frame of the open recording as the image of the Wavelet tab (a stand-in until *Stack*).
    pub fn wavelet_set_source_frame(&self, index: u32) -> Result<SourceInfo> {
        Ok(self.inner.wavelet_set_source_frame(index)?.into())
    }

    /// Renders the preview of one area. `settings` of `None` gives the unprocessed image (*Before*).
    pub fn wavelet_preview(
        &self,
        settings: Option<WaveletSettings>,
        area: Region,
        mode: ColourMode,
    ) -> Result<WaveletPreview> {
        let settings = settings
            .map(planets_core::wavelet::WaveletSettings::try_from)
            .transpose()?;
        Ok(self
            .inner
            .wavelet_preview(settings.as_ref(), area.into(), mode.into())?
            .into())
    }

    /// *Do All*: applies the settings to the whole image and keeps the result for saving. Blocks
    /// until done; stops on `cancel(SessionOperation::Wavelet)`.
    pub fn wavelet_do_all(
        &self,
        settings: WaveletSettings,
        mode: ColourMode,
        progress: Arc<dyn ProgressListener>,
    ) -> Result<RgbaImage> {
        let settings = planets_core::wavelet::WaveletSettings::try_from(settings)?;
        Ok(self
            .inner
            .wavelet_do_all(&settings, mode.into(), &ListenerSink(progress))?
            .into())
    }

    // --- Colour and tone -----------------------------------------------------------------------

    /// Takes the image the colour panels work on: RGBA bytes of `width` x `height`.
    pub fn set_color_source(&self, width: u32, height: u32, rgba: Vec<u8>) -> Result<SourceInfo> {
        Ok(self.inner.set_color_source(width, height, &rgba)?.into())
    }

    /// *RGB Align*, automatic: how far red and blue have to move to lie on green.
    pub fn estimate_rgb_align(&self, max_shift: u32) -> Result<ChannelShifts> {
        Ok(self.inner.estimate_rgb_align(max_shift)?.into())
    }

    /// Applies all panel settings to the source and keeps the result for saving.
    pub fn apply_colors(&self, settings: ColorSettings) -> Result<RgbaImage> {
        Ok(self.inner.apply_colors(&settings.into())?.into())
    }

    /// The preview of *Masking*: the colour source with the part the sharpening applies to tinted blue.
    pub fn refine_mask_overlay(&self, settings: RefineSettings) -> Result<RgbaImage> {
        Ok(self.inner.refine_mask_overlay(&settings.into())?.into())
    }

    /// The histogram as the *Histogram* panel shows it; with `after` the final result.
    pub fn color_histogram(&self, settings: ColorSettings, after: bool) -> Result<HistogramData> {
        Ok(self.inner.color_histogram(&settings.into(), after)?.into())
    }

    /// *Histogram*, automatic: black and white point that cut off `clip` percent at each end.
    pub fn auto_histogram_points(
        &self,
        settings: ColorSettings,
        clip: f32,
    ) -> Result<HistogramPoints> {
        Ok(self
            .inner
            .auto_histogram_points(&settings.into(), clip)?
            .into())
    }

    // --- Save ----------------------------------------------------------------------------------

    /// Fails if there is no image of `source` to save, so the app can fail before it opens a dialog.
    pub fn require_image(&self, source: ImageSource) -> Result<()> {
        Ok(self.inner.require_image(source.into())?)
    }

    /// Writes the image of `source` to `path` in `format`; with `adjustments` as the colour panels show
    /// it, and with `crop` only that part of the image. Returns the path that was written (the extension is
    /// corrected to match the format). With `geometry` the picture is flipped and rotated first (the crop is set on the result) and
    /// resized last.
    pub fn save_image(
        &self,
        source: ImageSource,
        format: ExportFormat,
        path: String,
        adjustments: Option<ColorSettings>,
        crop: Option<CropRect>,
        geometry: Option<GeometrySettings>,
    ) -> Result<String> {
        Ok(self.inner.save_image(
            source.into(),
            format.into(),
            Path::new(&path),
            adjustments.map(Into::into).as_ref(),
            crop.map(Into::into),
            geometry.map(Into::into).as_ref(),
        )?)
    }

    /// The preview of *Flip and Rotate*: `rgba` (`width` x `height`) flipped and rotated; a free angle makes the canvas bigger.
    pub fn orient_preview(
        &self,
        width: u32,
        height: u32,
        rgba: Vec<u8>,
        orientation: OrientationSettings,
    ) -> Result<RgbaImage> {
        Ok(self
            .inner
            .orient_preview(width, height, &rgba, &orientation.into())?
            .into())
    }

    /// *Save Aligned*: every frame that stays, moved onto the reference frame, as an AVI. Blocks until
    /// done; stops on `cancel(SessionOperation::Sequence)` (the same flag as `SessionOperation::Stack`).
    pub fn save_aligned(
        &self,
        path: String,
        settings: SequenceSettings,
        progress: Arc<dyn ProgressListener>,
    ) -> Result<SavedVideo> {
        Ok(self
            .inner
            .save_aligned(Path::new(&path), &settings.into(), &ListenerSink(progress))?
            .into())
    }

    /// *Save Integrated*: the moving average over *Average of n Frames* aligned frames, as an AVI.
    pub fn save_integrated(
        &self,
        path: String,
        settings: SequenceSettings,
        progress: Arc<dyn ProgressListener>,
    ) -> Result<SavedVideo> {
        Ok(self
            .inner
            .save_integrated(Path::new(&path), &settings.into(), &ListenerSink(progress))?
            .into())
    }

    // --- Cancel, Pause, CPUs -------------------------------------------------------------------

    /// Stops a running operation; it then returns `PlanetsError::Cancelled`. Without a running
    /// operation the Cancel is forgotten when the next one starts.
    pub fn cancel(&self, operation: SessionOperation) {
        self.inner.cancel(operation.into());
    }

    /// Pauses or resumes a running operation.
    pub fn pause(&self, operation: SessionOperation, paused: bool) {
        self.inner.pause(operation.into(), paused);
    }

    /// The number of logical cores: the default and the upper end of the *CPUs* field.
    pub fn cpu_count(&self) -> u64 {
        self.inner.cpu_count() as u64
    }

    /// *CPUs*: from now on the calculations use this many threads. Returns the number in use, which
    /// differs from `count` when that was outside 1 to the number of logical cores.
    pub fn set_cpus(&self, count: u32) -> Result<u64> {
        Ok(self.inner.set_cpus(count)? as u64)
    }

    /// The number of threads the calculations use now.
    pub fn cpus(&self) -> u64 {
        self.inner.cpus() as u64
    }
}

// --- Free functions --------------------------------------------------------------------------

/// The file types *Save image* offers for the given tab, in the order of the reference program.
#[uniffi::export]
pub fn export_formats(source: ImageSource) -> Vec<FormatInfo> {
    session::export_formats(source.into())
        .into_iter()
        .map(Into::into)
        .collect()
}

/// Writes the project (the extension `.rkproj` is added when missing); returns the path written.
#[uniffi::export]
pub fn project_save(project: Project, path: String) -> Result<String> {
    let project = planets_io::project::Project::try_from(project)?;
    Ok(session::project_save(&project, Path::new(&path))?)
}

/// Reads the project at `path`.
#[uniffi::export]
pub fn project_load(path: String) -> Result<LoadedProject> {
    Ok(session::project_load(Path::new(&path))?.into())
}

/// The wavelet settings *Reset Wavelets* restores.
#[uniffi::export]
pub fn wavelet_default_settings() -> WaveletSettings {
    session::wavelet_default_settings().into()
}

/// *Save Scheme*: writes the wavelet settings to a `.rwv` file.
#[uniffi::export]
pub fn save_wavelet_scheme(path: String, settings: WaveletSettings) -> Result<()> {
    let settings = planets_core::wavelet::WaveletSettings::try_from(settings)?;
    Ok(session::save_wavelet_scheme(Path::new(&path), &settings)?)
}

/// *Load Scheme*: reads the wavelet settings from a `.rwv` file.
#[uniffi::export]
pub fn load_wavelet_scheme(path: String) -> Result<WaveletSettings> {
    Ok(session::load_wavelet_scheme(Path::new(&path))?.into())
}

/// The size of a picture of `width` x `height` after *Flip and Rotate*.
#[uniffi::export]
pub fn orientation_size(width: u32, height: u32, orientation: OrientationSettings) -> ImageSize {
    let (width, height) = session::Orientation::from(orientation).output_size(width, height);
    ImageSize { width, height }
}

/// The size of a picture of `width` x `height` after *Resize Image*.
#[uniffi::export]
pub fn resize_size(width: u32, height: u32, resize: ResizeSettings) -> ImageSize {
    let (width, height) = session::Resize::from(resize).output_size(width, height);
    ImageSize { width, height }
}

/// `path` with the extension `.avi` added when it is missing.
#[uniffi::export]
pub fn with_avi_extension(path: String) -> String {
    session::with_avi_extension(Path::new(&path))
        .to_string_lossy()
        .into_owned()
}
